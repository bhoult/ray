"""Recursive trees of *seam networks* on the sphere (generalised horned spheres).

A seam network is a graph of curves on the unit sphere that cuts it into
panels (the seams of a ball).  A ``SeamTree`` hangs a copy ``shrink`` times
smaller on every *site* of the network (a rotation axis of its symmetry
group): the copy's own site 0 is turned back onto the parent's site (and sunk
by ``sink``), then the copy is spun about that axis by ``turn``.  The root
spends all its sites; every later network spends site 0 on its parent.

Subclasses fill in the curves, the panels (for colour), the sites and the
symmetry group:  ``TriondaHorned`` (trionda_horned.py, tetrahedral T) and
``HatTrickHorned`` (hattrick_horned.py, icosahedral I).

Distance: min over networks of ``smin(parent, network)``, searched level by
level with bounds, like ``ClaspTree``.  Each network is its seam tubes
(radius ``tube``) plus, if ``body`` > 0, a solid ball of radius ``body`` just
inside the seams so the seams stand out as ridges.  The trap value says what
was hit: a seam, or which panel of which generation (see ``cmap``).
"""
from __future__ import annotations

import colorsys

import numpy as np
from scipy.spatial import cKDTree

from .core import Field
from .clasptree import _smin


def rot(axis, ang) -> np.ndarray:
    a = np.asarray(axis, float); a = a / np.linalg.norm(a)
    K = np.array([[0, -a[2], a[1]], [a[2], 0, -a[0]], [-a[1], a[0], 0]])
    return np.eye(3) + np.sin(ang) * K + (1 - np.cos(ang)) * K @ K


def closure(gens, size=None) -> list[np.ndarray]:
    """Group of 3x3 orthogonal matrices generated by ``gens`` (rotations and/or reflections)."""
    G = [np.eye(3)]
    grew = True
    while grew:
        grew = False
        for g in list(G):
            for h in gens:
                m = h @ g
                if not any(np.allclose(m, x, atol=1e-8) for x in G):
                    G.append(m); grew = True
    if size is not None:
        assert len(G) == size, (len(G), size)
    return G


def reflection(normal) -> np.ndarray:
    n = np.asarray(normal, float); n = n / np.linalg.norm(n)
    return np.eye(3) - 2 * np.outer(n, n)


def group_from_sites(sites: np.ndarray, order: int, size: int) -> list[np.ndarray]:
    """Rotation group generated by ``order``-fold turns about site 0 and its nearest neighbour."""
    j = 1 + int(np.argmax(sites[1:] @ sites[0]))
    gens = [rot(sites[0], 2 * np.pi / order), rot(sites[j], 2 * np.pi / order)]
    G = [np.eye(3)]
    grew = True
    while grew:
        grew = False
        for g in list(G):
            for h in gens:
                m = h @ g
                if not any(np.allclose(m, x, atol=1e-8) for x in G):
                    G.append(m); grew = True
    assert len(G) == size, len(G)
    return G


def densify_arc(P: np.ndarray, step: float, closed: bool = False) -> np.ndarray:
    """Points along a polyline of unit vectors, great-arc interpolated every ~``step`` radians."""
    out = []
    n = len(P)
    for i in range(n if closed else n - 1):
        a, b = P[i], P[(i + 1) % n]
        om = np.arccos(np.clip(a @ b, -1, 1))
        m = max(1, int(np.ceil(om / step)))
        t = np.arange(m) / m
        if om < 1e-9:
            out.append(np.tile(a, (m, 1)))
        else:
            out.append((np.sin((1 - t) * om)[:, None] * a + np.sin(t * om)[:, None] * b) / np.sin(om))
    out.append(P[:1] if closed else P[-1:])
    return np.vstack(out)


def fibonacci(n: int) -> np.ndarray:
    k = np.arange(n) + 0.5
    z = 1 - 2 * k / n
    r = np.sqrt(1 - z * z); ph = np.pi * (1 + 5 ** 0.5) * k
    return np.stack([r * np.cos(ph), r * np.sin(ph), z], -1)


class SeamTree(Field):
    bound = 2.0
    n_classes = 1        # panel colour classes per generation
    root_site0 = True    # False: the root also keeps site 0 free (no child there), like every later network

    def setup(self, curves, panels, classes, sites, group, order, shrink, sink, turn, tube, body,
              blend, iters, lookup=40000, lateral=0.0, lean=0.0):
        """curves: seam polylines on the unit sphere; panels: closed polylines (one per panel);
        classes: colour class of each panel; sites: (K,3) axes; group: rotations; order: fold of site 0."""
        self.s, self.sink, self.turn = float(shrink), float(sink), float(turn)
        self.tube, self.body, self.blend, self.iters = float(tube), float(body), float(blend), int(iters)
        self.curves, self.panels, self.classes, self.sites = curves, panels, np.asarray(classes), np.asarray(sites, float)
        pts = np.vstack([densify_arc(c, 0.004) for c in curves])
        self.tree = cKDTree(pts)
        # panel lookup on the sphere: label a point cloud by polygon containment, nearest label elsewhere
        from matplotlib.path import Path
        X = fibonacci(lookup)
        lab = np.full(len(X), -1)
        for k, poly in enumerate(panels):
            c = poly.mean(0); c /= np.linalg.norm(c)
            rad = np.arccos(np.clip(poly @ c, -1, 1)).max()
            near = np.nonzero(X @ c > np.cos(min(rad * 1.2, 1.5)))[0]
            e1 = np.cross(c, [0.31, 0.57, 0.76]); e1 /= np.linalg.norm(e1); e2 = np.cross(c, e1)
            g = lambda Q: np.stack([Q @ e1, Q @ e2], -1) / (Q @ c)[:, None]
            inside = Path(g(poly)).contains_points(g(X[near]))
            lab[near[inside]] = k
        ok = lab >= 0
        self.coverage = ok.mean()
        _, j = cKDTree(X[ok]).query(X[~ok]) if (~ok).any() else (None, [])
        lab[~ok] = lab[ok][j]
        self.lookup = cKDTree(X); self.lookup_cls = self.classes[lab]
        # child maps
        u0 = self.sites[0]
        # with mirrors through site 0 (groups with reflections) the child's half turn is taken about the tangent that
        # lies in a mirror plane, so that mirror fixes a child that is not turned and not leaning out of the plane
        mir = [g for g in group if np.linalg.det(g) < 0 and np.allclose(g @ u0, u0, atol=1e-8)]
        if mir:
            P = (np.eye(3) - mir[0]) / 2
            n = P[:, int(np.argmax(np.linalg.norm(P, axis=0)))]; n /= np.linalg.norm(n)
            self.mirror_tangent = np.cross(u0, n); self.mirror_tangent /= np.linalg.norm(self.mirror_tangent)
        else:
            self.mirror_tangent = None
        flip = rot(self.mirror_tangent if mir else np.cross(u0, [0.3, 0.5, 0.8]), np.pi)
        R0 = rot(u0, np.radians(turn)) @ flip
        # where a child hangs (site 0's frame): on the axis, pushed out by ``sink``, and ``lateral`` (in units of
        # the child's size) sideways along a tangent turned by ``lean`` degrees, so that siblings reach for each other
        e0 = self.mirror_tangent if self.mirror_tangent is not None else np.cross(self.sites[0], [0.3, 0.5, 0.8])
        e0 = e0 / np.linalg.norm(e0)
        off = self.sites[0] * (1.0 + self.sink * self.s) + lateral * self.s * (rot(self.sites[0], np.radians(lean)) @ e0)
        # one child per site, or (lateral > 0) one per group element, i.e. a symmetric cluster of n_fold children
        # around every site, which is what lets siblings clasp each other
        self.maps, self.map_site = [], []
        self.group, self.order = group, order
        probe = self.tree.data[:: max(1, len(self.tree.data) // 300)]
        for g in group:
            k = int(np.argmin(np.linalg.norm(self.sites - g @ self.sites[0], axis=1)))
            if lateral == 0 and k in self.map_site:
                continue
            Rk, tk = g @ R0, g @ off
            if any(np.allclose(tk, t, atol=1e-8) and self.tree.query(probe @ (R.T @ Rk).T)[0].max() < 1e-3
                   for R, t in self.maps):
                continue                                     # same place, same network: a mirror may fix a child
            self.maps.append((Rk, tk)); self.map_site.append(k)
        reach = max(float(np.linalg.norm(t)) for _, t in self.maps)
        self.rb = max(1.0 + self.tube, reach / (1.0 - self.s)) + 1e-3
        self.bound = self.rb * 1.02
        self.n_bands = 1 + self.iters * self.n_classes

    # -- colours -----------------------------------------------------------------
    def class_color(self, gen: int, cls: int):
        h = (cls / max(self.n_classes, 1) * 0.75 + 0.07 + gen * 0.19) % 1.0
        return colorsys.hsv_to_rgb(h, 0.62, max(0.45, 0.98 - 0.12 * gen))

    def cmap(self):
        """Colormap for ``render(..., palette=tree.cmap(), trap_weight=0.85)``: seams dark, one colour per (generation, class)."""
        from matplotlib.colors import ListedColormap
        cols = np.zeros((1024, 3))
        x = np.linspace(0, 1, 1024)
        cols[:] = (0.08, 0.08, 0.10)
        for i, xv in enumerate(x):
            if xv >= 0.15:
                b = min(int((xv - 0.15) / 0.85 * self.n_bands), self.n_bands - 1)
                if b > 0:
                    gen, cls = divmod(b - 1, self.n_classes)
                    cols[i] = self.class_color(gen, cls)
        return ListedColormap(cols)

    def _band(self, gen: int, cls) -> np.ndarray:
        return 1 + gen * self.n_classes + cls

    # -- one network ---------------------------------------------------------------
    def net(self, q):
        return self.tree.query(q)[0] - self.tube

    def subtree(self, q):
        r = np.linalg.norm(q, axis=1)
        sub = np.minimum(np.abs(r - 1.0) - self.tube, np.abs(r - self.body) if self.body > 0 else 9.0)
        return np.minimum(sub, r - self.rb)

    def _de(self, P):
        N = len(P)
        s, tube, blend = self.s, self.tube, self.blend
        idx = np.arange(N)
        q = np.asarray(P, float).copy()
        sc = np.ones(N)
        dp = np.full(N, 1e9)
        bd = np.full(N, -1e9)
        best = np.full(N, 1e9)
        plain = np.full(N, 1e9)
        band = np.zeros(N)
        for gen in range(self.iters):
            if len(idx) == 0:
                break
            kf = blend * tube * sc
            keep = bd < best[idx] + kf
            idx, q, sc, dp, kf = idx[keep], q[keep], sc[keep], dp[keep], kf[keep]
            if len(idx) == 0:
                break
            dt = self.net(q) * sc
            d, cand = dt, np.zeros(len(idx))
            if self.body > 0:
                r = np.linalg.norm(q, axis=1)
                dsh = (r - self.body) * sc
                d = _smin(dt, dsh, 0.5 * kf)
                near_shell = dsh < dt
                if near_shell.any():
                    cls = self.lookup_cls[self.lookup.query(q[near_shell] / np.maximum(r[near_shell], 1e-9)[:, None])[1]]
                    cand[near_shell] = self._band(gen, cls)
            gmin = np.full(N, np.inf)
            np.minimum.at(gmin, idx, d)
            better = gmin < plain
            plain = np.where(better, gmin, plain)
            # trap of the nearest piece: the node whose d equals the point's min
            win = d <= gmin[idx] + 1e-12
            band[idx[win & better[idx]]] = cand[win & better[idx]]
            np.minimum.at(best, idx, _smin(dp, d, kf))
            if gen + 1 >= self.iters:
                break
            sc2 = sc * s
            reach_k = blend * tube * sc2
            nidx, nq, nsc, ndp, nbd = [], [], [], [], []
            for k, (R, t) in enumerate(self.maps):
                if (gen > 0 or not self.root_site0) and self.map_site[k] == 0:
                    continue
                c = ((q - t) @ R) / s
                bound = self.subtree(c) * sc2
                m = bound < best[idx] + reach_k
                nidx.append(idx[m]); nq.append(c[m]); nsc.append(sc2[m]); ndp.append(d[m]); nbd.append(bound[m])
            idx, q, sc, dp, bd = (np.concatenate(v) for v in (nidx, nq, nsc, ndp, nbd))
        return best, np.where(band > 0, (band + 0.5) / self.n_bands, 0.0)

    # -- the tree as curves ----------------------------------------------------------
    def networks(self, depth: int = 2):
        """Poses ``(M, t, S, gen, parent)`` of the networks of generations 0..depth (own frame -> world)."""
        poses = [(np.eye(3), np.zeros(3), 1.0, 0, -1)]
        frontier = [0]
        for gen in range(depth):
            nxt = []
            for pi in frontier:
                M, t, S = poses[pi][:3]
                for k, (R, tc) in enumerate(self.maps):
                    if (gen > 0 or not self.root_site0) and self.map_site[k] == 0:
                        continue
                    poses.append((M @ R, t + S * (M @ tc), S * self.s, gen + 1, pi)); nxt.append(len(poses) - 1)
            frontier = nxt
        return poses

    def seams(self, depth: int = 2):
        return [(gen, t + S * c @ M.T) for M, t, S, gen, _ in self.networks(depth) for c in self.curves]

    def panel_loops(self, depth: int = 1):
        """Panel boundaries as closed curves, with the (network index, panel index) of each."""
        out, who = [], []
        for n, (M, t, S, gen, _) in enumerate(self.networks(depth)):
            for k, p in enumerate(self.panels):
                out.append(t + S * densify_arc(p, 0.05, closed=True)[:-1] @ M.T); who.append((n, k))
        return out, who
